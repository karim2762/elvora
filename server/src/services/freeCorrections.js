// Stage 10A Part 2 — FREE administrative corrections. A correction fixes an ELVORA error using existing evidence; it can never create completion, invent dates
// or take a fee (free_corrections.fee_paise is CHECKed to 0). The original document is never edited or deleted: a corrected certificate is generated by the
// existing Stage 06 renderer, the old one becomes Revoked-with-replacement ("Superseded"), and both stay traceable. Everything that must change together
// (data fix, supersession, new document, link, notification, audit) commits in ONE transaction; the PDF is rendered and stored BEFORE it, and removed if it fails.
export const FREE_NOTICE = 'Administrative corrections caused by ELVORA errors are processed free of charge.';
export const CATEGORIES = Object.freeze({
  student_name: 'Incorrect student name on certificate',
  internship_dates: 'Incorrect internship dates',
  academic_info: 'Incorrect academic information',
  wrong_application: 'Wrong application associated with a document',
  document_service_error: 'Incorrect information generated by the document service',
  certificate_details: 'Incorrect certificate details requiring replacement',
});
const DATA_CATEGORIES = ['student_name', 'internship_dates', 'academic_info'];
const ACADEMIC_FIELDS = ['college', 'degree', 'branch', 'academicYear', 'graduationYear'];
const conflict = (message, code, details) => new HttpError(409, message, { code, details });
const clean = (v, min, max, field) => {
  const s = typeof v === 'string' ? v.replace(/[\u0000-\u001f\u007f]/g, ' ').replace(/\s+/g, ' ').trim() : '';
  if (s.length < min || s.length > max) throw badRequest(`${field} must be ${min}–${max} characters.`, { [field]: `Required, ${min}–${max} characters` });
  return s;
};
const validDate = (s) => typeof s === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(s) && !Number.isNaN(Date.parse(`${s}T00:00:00Z`)) && new Date(`${s}T00:00:00Z`).toISOString().startsWith(s);
const dayNum = (d) => Math.floor(Date.parse(`${String(d).slice(0, 10)}T00:00:00Z`) / 86400000);

const studentCurrent = (s) => ({ fullName: s.fullName, college: s.college, degree: s.degree, branch: s.branch, academicYear: s.academicYear, graduationYear: s.graduationYear });
const enrollmentCurrent = (e) => ({ startDate: e.startDate, completedAt: e.completedAt });

// Parses the admin's request into { originalValues, correctedValues } for the category. Original values are read from the database, never from the client.
function planValues(category, body, student, enrollment, oldDoc) {
  if (category === 'student_name') {
    const name = clean(body?.corrected?.fullName, 2, 100, 'fullName');
    if (!/^[\p{L}][\p{L}\p{M} .'’-]*$/u.test(name)) throw badRequest('The corrected name contains characters that can’t appear on a certificate.', { fullName: 'Letters, spaces, . - \' only' });
    if (name === student.fullName) throw badRequest('The corrected name is the same as the current one.', { fullName: 'No change' });
    return { original: { fullName: student.fullName }, corrected: { fullName: name } };
  }
  if (category === 'internship_dates') {
    const o = enrollmentCurrent(enrollment); const c = {};
    if (body?.corrected?.startDate !== undefined) { if (!validDate(body.corrected.startDate)) throw badRequest('Use a start date like 2026-01-05.', { startDate: 'Invalid date' }); c.startDate = body.corrected.startDate; }
    if (body?.corrected?.completedAt !== undefined) { if (!validDate(body.corrected.completedAt)) throw badRequest('Use a completion date like 2026-06-30.', { completedAt: 'Invalid date' }); c.completedAt = `${body.corrected.completedAt}${String(enrollment.completedAt).slice(10) || 'T00:00:00.000Z'}`; }
    const changed = Object.keys(c).filter((k) => String(c[k]).slice(0, 10) !== String(o[k]).slice(0, 10));
    if (!changed.length) throw badRequest('Nothing to correct: the dates are the same as the record.', { corrected: 'No change' });
    return { original: Object.fromEntries(changed.map((k) => [k, o[k]])), corrected: Object.fromEntries(changed.map((k) => [k, c[k]])) };
  }
  if (category === 'academic_info') {
    const o = studentCurrent(student); const c = {};
    for (const f of ACADEMIC_FIELDS) {
      const v = body?.corrected?.[f]; if (v === undefined) continue;
      c[f] = f === 'graduationYear' ? Number(v) : clean(v, 1, 120, f);
      if (f === 'graduationYear' && (!Number.isInteger(c[f]) || c[f] < 2000 || c[f] > 2100)) throw badRequest('Enter a valid graduation year.', { graduationYear: 'Invalid year' });
    }
    const changed = Object.keys(c).filter((k) => c[k] !== o[k]);
    if (!changed.length) throw badRequest('Nothing to correct: the values are the same as the record.', { corrected: 'No change' });
    return { original: Object.fromEntries(changed.map((k) => [k, o[k]])), corrected: Object.fromEntries(changed.map((k) => [k, c[k]])) };
  }
  // Regeneration categories: no stored field is edited. The original is the issued document's frozen snapshot; the "corrected" value is what the current
  // verified records produce. Reissue is refused unless they actually differ (checked again at approval time).
  return { original: { documentNumber: oldDoc.documentNumber, snapshot: oldDoc.snapshot }, corrected: { regenerateFromRecords: true } };
}

// The records as they WOULD be after the correction. Used for validation and rendering; nothing is written until the final transaction.
function overlay(student, enrollment, corrected) {
  const s = { ...student }; const e = { ...enrollment };
  for (const [k, v] of Object.entries(corrected)) { if (k in studentCurrent(student)) s[k] = v; else if (k === 'startDate' || k === 'completedAt') e[k] = v; }
  return { student: s, enrollment: e };
}
// Evidence-based limits for date corrections: only a record that is ALREADY genuinely completed can have its dates fixed, never made complete,
// and the corrected dates must still show the full required duration and can't be in the future.
function assertDatesStillGenuine(enrollment, e2) {
  const required = enrollment.internship.durationDays;
  if (enrollment.status !== 'Completed' || !enrollment.completedAt) throw conflict('Dates can only be corrected on an internship already approved as completed.', 'NOT_COMPLETED');
  if (!e2.startDate || dayNum(e2.completedAt) < dayNum(e2.startDate)) throw conflict('The corrected completion date can’t be before the start date.', 'COMPLETION_BEFORE_START');
  if (dayNum(e2.completedAt) > dayNum(new Date().toISOString())) throw conflict('A completion date in the future is not allowed.', 'FUTURE_DATE');
  const served = dayNum(e2.completedAt) - dayNum(e2.startDate) + 1;
  if (served < required) throw conflict(`The corrected dates show ${served} days; this internship requires ${required}. A correction can’t shorten an internship.`, 'DURATION_NOT_MET');
}

// ---------- authorization (Stage 10C Part 2) ----------
// Corrections replace an issued, publicly verifiable certificate, so being "an administrator" is not enough: the signed-in administrator must hold the
// 'certificate.correct' permission (a database grant only; PAYMENT_ADMIN_EMAILS does NOT imply it, and the shared API key never qualifies).
// Checked in the route AND again here. Separation of duties: the administrator who created a correction can never approve it.
export const CORRECTION_PERMISSION = 'certificate.correct';
export const canCorrect = (admin) => admin?.via === 'session' && Boolean(admin.id) && Pay.hasPermission(admin.id, CORRECTION_PERMISSION);
export function assertCanCorrect(admin) {
  if (canCorrect(admin)) return;
  try { audit.record({ admin, action: 'admin.access_denied', targetType: 'permission', targetId: CORRECTION_PERMISSION, result: 'failure', reason: 'missing permission' }); } catch { /* never block the 403 */ }
  throw new HttpError(403, 'You do not have permission to manage certificate corrections.', { code: 'PERMISSION_REQUIRED' });
}
export const requireCorrectionPermission = (req, _res, next) => { try { assertCanCorrect(req.admin); next(); } catch (e) { next(e); } };

// ---------- create ----------
export function createCorrection(admin, body) {
  assertCanCorrect(admin);
  const category = body?.category;
  if (!Object.keys(CATEGORIES).includes(category)) throw badRequest('Choose a correction category.', { category: 'Unknown category' });
  if (typeof body?.documentId !== 'string' || !DOCUMENT_ID_RE.test(body.documentId)) throw badRequest('Choose the document to correct.', { documentId: 'Required' });
  if (body?.confirm !== true) throw badRequest('Confirm that this correction is for an ELVORA error and is supported by evidence.', { confirm: 'Required' });
  const reason = clean(body?.reason, 10, 500, 'reason'); const evidence = clean(body?.evidence, 10, 1000, 'evidence');
  return db.transaction(() => {
    const doc = docs.findAny(body.documentId);
    if (!doc) throw notFound('Document not found', 'DOCUMENT_NOT_FOUND');
    if (typeof body.studentId !== 'string' || body.studentId !== doc.studentId) throw conflict('That document does not belong to the selected student.', 'OWNERSHIP_MISMATCH');
    if (doc.type !== 'certificate') throw conflict('Free corrections currently replace certificates only.', 'UNSUPPORTED_TYPE');
    if (doc.status !== 'Issued') throw conflict('Only a currently valid issued certificate can be corrected.', 'NOT_ISSUED');
    if (A.openCorrectionForDocument(doc.id)) throw conflict('A correction for this document is already open.', 'CORRECTION_OPEN');
    const { enrollment, student } = loadTrusted(doc.enrollmentId);
    const { original, corrected } = planValues(category, body, student, enrollment, doc);
    if (category === 'internship_dates') assertDatesStillGenuine(enrollment, overlay(student, enrollment, corrected).enrollment);
    const id = A.insertCorrection({ studentId: student.id, enrollmentId: enrollment.id, documentId: doc.id, category, reason, evidence, originalValues: original, correctedValues: corrected, originalSnapshot: doc.snapshot, adminId: admin.id, adminName: admin.fullName ?? 'Administrator' });
    audit.record({ admin, action: 'correction.create', targetType: 'correction', targetId: id, reason: `${category}; doc ${doc.id}; free; ${reason}` });
    notify({ studentId: student.id, type: 'correction_created', title: 'A free correction was started', message: 'ELVORA is correcting an error on one of your documents. This is free of charge. You will be told when the corrected certificate is ready.', applicationId: enrollment.applicationId, enrollmentId: enrollment.id, documentId: doc.id, dedupeKey: `cor:${id}:created` });
    audit.record({ admin, action: 'priority.notify', targetType: 'correction', targetId: id, reason: 'correction_created' });
    return correctionView(id);
  })();
}

// ---------- approve → reissue ----------
export async function approveCorrection(admin, id) {
  assertCanCorrect(admin);
  // Separation of duties: checked before anything changes, and the refusal is audited outside any transaction so it is never rolled back with one.
  const pre = A.correctionById(id); if (!pre) throw notFound('Correction not found', 'CORRECTION_NOT_FOUND');
  if (pre.createdBy && pre.createdBy === admin.id) {
    try { audit.record({ admin, action: 'correction.approve', targetType: 'correction', targetId: id, result: 'failure', reason: 'self-approval refused; a second authorized administrator must approve' }); } catch { /* never block the 403 */ }
    throw new HttpError(403, 'The administrator who created a correction cannot approve it. A second authorized administrator must approve it, and the request stays pending until then.', { code: 'SELF_APPROVAL_FORBIDDEN' });
  }
  const claimed = db.transaction(() => {
    const c = A.correctionById(id); if (!c) throw notFound('Correction not found', 'CORRECTION_NOT_FOUND');
    if (!A.setCorrectionStatus(id, ['Pending Approval', 'Failed'], 'Processing', { note: 'Approved; generating the corrected certificate.', approvedBy: admin.id ?? null, approvedByName: admin.fullName ?? 'Administrator' })) throw conflict(`This correction is ${c.status} and can’t be processed.`, 'INVALID_STATE');
    audit.record({ admin, action: 'correction.approve', targetType: 'correction', targetId: id, reason: `doc ${c.documentId}; created by ${c.createdBy ?? 'unknown'}; approved by ${admin.id ?? 'unknown'}` });
    return c;
  })();
  try { return await reissue(admin, claimed); } catch (err) {
    // Nothing in the document tables was touched (the final transaction rolled back or was never reached); the correction goes to Failed and can be retried.
    const code = err?.code ?? 'ERROR';
    try { db.transaction(() => { A.setCorrectionStatus(id, 'Processing', 'Failed', { note: `Reissue failed: ${code}`, failureCode: String(code).slice(0, 60) }); audit.record({ admin, action: 'correction.reissue', targetType: 'correction', targetId: id, result: 'failure', reason: code }); })(); } catch (e) { console.error('[correction] could not record a failure:', e.message); }
    throw err;
  }
}

async function reissue(admin, c) {
  const old = docs.findAny(c.documentId);
  if (!old || old.status !== 'Issued' || old.type !== 'certificate') throw conflict('The original certificate is no longer the valid issued certificate.', 'NOT_ISSUED');
  const { enrollment, student } = loadTrusted(old.enrollmentId);
  if (student.id !== c.studentId || enrollment.id !== c.enrollmentId) throw conflict('The records no longer match this correction.', 'RECORD_MISMATCH');
  // The data must still be exactly what the correction recorded as "original" (nobody changed it in between).
  const nowOriginal = c.category === 'student_name' || c.category === 'academic_info' ? studentCurrent(student) : enrollmentCurrent(enrollment);
  if (DATA_CATEGORIES.includes(c.category)) for (const [k, v] of Object.entries(c.originalValues)) if (String(nowOriginal[k]) !== String(v)) throw conflict('The record changed after this correction was created. Create a new correction.', 'STALE_ORIGINAL');
  const { student: s2, enrollment: e2 } = overlay(student, enrollment, DATA_CATEGORIES.includes(c.category) ? c.correctedValues : {});
  if (c.category === 'internship_dates') assertDatesStillGenuine(enrollment, e2);
  // Completion rules apply to the corrected certificate exactly as to a first issue.
  const verdict = checkEligibility({ type: 'certificate', enrollment: e2, existing: null, strict: true, requireApproval: true, taskGate: taskGate(e2) });
  if (!verdict.eligible) throw conflict(verdict.message, verdict.code);
  const newSnap = snapshotOf(e2, s2);
  if (!DATA_CATEGORIES.includes(c.category) && JSON.stringify(newSnap) === JSON.stringify(old.snapshot)) throw conflict('The verified records produce the same certificate content, so there is nothing to correct. Use the data corrections if a record is wrong.', 'NO_DIFFERENCE');
  const organization = getOrganization(); const missing = missingForIssuance(organization);
  if (missing.length) throw conflict('Organization details are incomplete. Open Admin → Settings first.', 'ORGANIZATION_INCOMPLETE', { missing });

  // Dry run first (cannot fit / unprintable characters are rejected before any number is used), then reserve the number once and render for real.
  await renderPdf(buildDocumentData('certificate', { enrollment: e2, student: s2, organization, document: { documentNumber: 'ELV-CRT-0000-000000', verificationCode: 'ELV-VER-AAAA-AAAA-AAAA', issuedAt: new Date().toISOString() } }));
  const fresh = A.correctionById(c.id);
  let number = fresh.reservedNumber; let code = fresh.reservedCode;
  if (!number) { number = allocateNumber('certificate'); code = newVerificationCode(); A.reserve(c.id, number, code); const r = A.correctionById(c.id); number = r.reservedNumber; code = r.reservedCode; }
  const issuedAt = new Date().toISOString();
  const pdf = await renderPdf(buildDocumentData('certificate', { enrollment: e2, student: s2, organization, document: { documentNumber: number, verificationCode: code, issuedAt } }));
  if (pdf.subarray(0, 5).toString('latin1') !== '%PDF-' || pdf.length > config.maxDocumentBytes) throw new HttpError(500, 'The generated PDF was not valid.', { code: 'PDF_INVALID' });
  const storageKey = storage.newKey(); storage.put(storageKey, pdf);
  try {
    return db.transaction(() => finalize({ admin, c, old, enrollment, student, s2, e2, newSnap, number, code, issuedAt, storageKey, pdf }))();
  } catch (err) { storage.remove(storageKey); throw err; }
}

function finalize({ admin, c, old, enrollment, student, s2, e2, newSnap, number, code, issuedAt, storageKey, pdf }) {
  const t = new Date().toISOString();
  // 1. re-verify inside the transaction (another request may have won)
  const cur = docs.findAny(old.id);
  if (!cur || cur.status !== 'Issued') throw conflict('The original certificate changed while the correction was running.', 'STALE_DOCUMENT');
  const cur2 = A.correctionById(c.id); if (cur2.status !== 'Processing') throw conflict('This correction is no longer being processed.', 'INVALID_STATE');
  // 2. apply the data fix (original values are already frozen in free_corrections)
  if (c.category === 'student_name' || c.category === 'academic_info') {
    const map = { fullName: 'full_name', college: 'college', degree: 'degree', branch: 'branch', academicYear: 'academic_year', graduationYear: 'graduation_year' };
    for (const [k, v] of Object.entries(c.correctedValues)) {
      const r = db.prepare(`UPDATE students SET ${map[k]} = ?, updated_at = ? WHERE id = ? AND ${map[k]} = ?`).run(v, t, student.id, c.originalValues[k]);
      if (!r.changes) throw conflict('The student record changed while the correction was running.', 'STALE_ORIGINAL');
    }
  } else if (c.category === 'internship_dates') {
    const map = { startDate: 'start_date', completedAt: 'completed_at' };
    for (const [k, v] of Object.entries(c.correctedValues)) {
      const r = db.prepare(`UPDATE enrollments SET ${map[k]} = ?, updated_at = ? WHERE id = ? AND ${map[k]} = ?`).run(v, t, enrollment.id, c.originalValues[k]);
      if (!r.changes) throw conflict('The internship record changed while the correction was running.', 'STALE_ORIGINAL');
    }
  }
  // 3. supersede the old document: it stays in `documents` (never deleted); the live-document unique index then lets the replacement exist
  const revoked = db.prepare("UPDATE documents SET status = 'Revoked', revoked_at = ?, revoked_reason = ?, revoked_by = ? WHERE id = ? AND status = 'Issued'")
    .run(t, `Superseded by ${number} (free correction ${c.id})`, 'ELVORA correction', old.id);
  if (!revoked.changes) throw conflict('The original certificate changed while the correction was running.', 'STALE_DOCUMENT');
  // 4. the replacement (Issued, own unique ID / number / verification reference)
  let newId = null;
  for (let i = 0; i < 5 && !newId; i++) {
    const tryId = newDocumentId();
    try {
      db.prepare(`INSERT INTO documents (id, student_id, enrollment_id, application_id, internship_id, type, status, title, document_number, verification_code, template_version, snapshot,
          storage_key, file_name, size_bytes, sha256, issued_by, created_at, issued_at) VALUES (?, ?, ?, ?, ?, 'certificate', 'Issued', ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`)
        .run(tryId, old.studentId, old.enrollmentId, old.applicationId, old.internshipId, DEFAULT_TITLES.certificate, number, code, TEMPLATE_VERSIONS.certificate, JSON.stringify(newSnap),
          storageKey, `ELVORA-Certificate-${old.enrollmentId}-corrected.pdf`, pdf.length, crypto.createHash('sha256').update(pdf).digest('hex'), admin.fullName ?? 'Administrator', t, issuedAt);
      newId = tryId;
    } catch (err) { if (!/documents\.id\b/.test(err?.message ?? '')) throw err; }
  }
  if (!newId) throw new Error('Could not generate a unique document ID');
  db.prepare('INSERT INTO document_replacements (old_document_id, new_document_id, correction_id, created_at) VALUES (?, ?, ?, ?)').run(old.id, newId, c.id, t);
  db.prepare('UPDATE enrollments SET certificate_id = ?, certificate_issued_at = ?, updated_at = ? WHERE id = ?').run(newId, issuedAt, t, enrollment.id);
  docs.addEvent(old.id, 'revoked', { actor: 'ELVORA correction', detail: `superseded by ${number}` });
  docs.addEvent(newId, 'created', { actor: admin.fullName ?? 'Administrator', detail: number });
  docs.addEvent(newId, 'issued', { actor: admin.fullName ?? 'Administrator', detail: `replaces ${old.documentNumber}; sha256:${crypto.createHash('sha256').update(pdf).digest('hex').slice(0, 16)}` });
  db.prepare('UPDATE free_corrections SET replacement_document_id = ?, new_snapshot = ? WHERE id = ?').run(newId, JSON.stringify(newSnap), c.id);
  A.setCorrectionStatus(c.id, 'Processing', 'Reissued', { note: `Replaced by ${number}.`, resolved: true });
  // 5. audit + student notification, in the same transaction
  audit.record({ admin, action: 'document.supersede', targetType: 'document', targetId: old.id, reason: `by ${newId}; correction ${c.id}` });
  audit.record({ admin, action: 'correction.reissue', targetType: 'correction', targetId: c.id, reason: `new doc ${newId}; old doc ${old.id}` });
  audit.record({ admin, action: 'certificate.issue', targetType: 'document', targetId: newId, reason: `${number} (free correction)` });
  notify({ studentId: old.studentId, type: 'correction_reissued', title: 'Your corrected certificate is ready', message: 'ELVORA has corrected an error and issued a replacement certificate, free of charge. The earlier certificate is now marked as superseded.',
    applicationId: old.applicationId, enrollmentId: old.enrollmentId, documentId: newId, dedupeKey: `cor:${c.id}:reissued` });
  audit.record({ admin, action: 'priority.notify', targetType: 'correction', targetId: c.id, reason: `correction_reissued; doc ${newId}` });
  return correctionView(c.id);
}

export function cancelCorrection(admin, id, body) {
  assertCanCorrect(admin);
  const reason = clean(body?.reason, 10, 500, 'reason');
  return db.transaction(() => {
    const c = A.correctionById(id); if (!c) throw notFound('Correction not found', 'CORRECTION_NOT_FOUND');
    if (!A.setCorrectionStatus(id, ['Pending Approval', 'Failed'], 'Cancelled', { note: reason, resolved: true })) throw conflict(`This correction is ${c.status} and can’t be cancelled.`, 'INVALID_STATE');
    audit.record({ admin, action: 'correction.cancel', targetType: 'correction', targetId: id, reason });
    return correctionView(id);
  })();
}

// ---------- reads ----------
export function correctionView(id) {
  const c = A.correctionById(id); if (!c) throw notFound('Correction not found', 'CORRECTION_NOT_FOUND');
  const oldDoc = docs.findAny(c.documentId); const newDoc = c.replacementDocumentId ? docs.findAny(c.replacementDocumentId) : null;
  const brief = (d) => d && { id: d.id, documentNumber: d.documentNumber, verificationCode: d.verificationCode, status: d.status, issuedAt: d.issuedAt };
  return { ...c, categoryLabel: CATEGORIES[c.category], notice: FREE_NOTICE, originalDocument: brief(oldDoc), replacementDocument: brief(newDoc), history: A.correctionHistory(id), audit: audit.forTarget('correction', id, 50) };
}
export function listCorrections(query = {}) {
  const one = (k) => (typeof query[k] === 'string' && query[k].trim() !== '' && query[k] !== 'All' ? query[k].trim().slice(0, 80) : null);
  const status = one('status'); const errors = {};
  if (status && !['Pending Approval', 'Processing', 'Reissued', 'Failed', 'Cancelled'].includes(status)) errors.status = 'Unknown status';
  const num = (k, d, min, max) => { const v = query[k]; if (v === undefined || v === '') return d; const n = Number(v); if (!Number.isInteger(n) || n < min || n > max) { errors[k] = `Use a whole number from ${min} to ${max}`; return d; } return n; };
  const pageSize = num('pageSize', 25, 1, 100); const wanted = num('page', 1, 1, 100000);
  if (Object.keys(errors).length) throw badRequest('Invalid filter', errors);
  const f = { status, student: one('student'), from: one('from'), to: one('to') };
  const total = A.pageCorrections({ ...f, limit: 1, offset: 0 }).total; const totalPages = Math.max(1, Math.ceil(total / pageSize)); const page = Math.min(wanted, totalPages);
  const { rows } = A.pageCorrections({ ...f, limit: pageSize, offset: (page - 1) * pageSize });
  return { corrections: rows.map((c) => ({ id: c.id, studentName: c.studentName, category: c.category, categoryLabel: CATEGORIES[c.category], status: c.status, free: true, documentId: c.documentId, createdByName: c.createdByName, createdAt: c.createdAt, updatedAt: c.updatedAt })), pagination: { page, pageSize, total, totalPages }, categories: CATEGORIES, notice: FREE_NOTICE };
}
// Form helpers: the student's current valid certificates (never drafts or other people's).
export function certificatesForStudent(studentId) {
  const s = students.findById(studentId); if (!s) throw notFound('Student not found', 'STUDENT_NOT_FOUND');
  return { student: { id: s.id, fullName: s.fullName }, documents: docs.listForAdmin({ type: 'certificate', status: 'Issued', limit: 100 }).filter((d) => d.studentId === studentId).map((d) => ({ id: d.id, documentNumber: d.documentNumber, title: d.title, issuedAt: d.issuedAt, internshipTitle: d.internship.title, enrollmentId: d.enrollmentId })) };
}

// Student view: only what the student needs. No admin names, no internal reasons/evidence, no audit.
export function studentCorrections(studentId) {
  return { notice: FREE_NOTICE, corrections: A.forStudent(studentId).map((c) => ({
    id: c.id, categoryLabel: CATEGORIES[c.category], status: c.status === 'Processing' ? 'In progress' : c.status === 'Pending Approval' ? 'Received' : c.status === 'Failed' ? 'In progress' : c.status,
    free: true, createdAt: c.createdAt, updatedAt: c.updatedAt, resolvedAt: c.resolvedAt,
    originalDocumentNumber: docs.findAny(c.documentId)?.documentNumber ?? null, replacementDocumentNumber: c.replacementDocumentId ? docs.findAny(c.replacementDocumentId)?.documentNumber ?? null : null })) };
}
